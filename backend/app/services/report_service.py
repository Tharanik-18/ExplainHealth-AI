"""
Clinical Assessment Report Generator for ExplainHealth AI
Generates downloadable HTML/PDF medical-style reports.
"""

import os
from datetime import datetime
from typing import Dict, Any, List, Optional
from jinja2 import Template

REPORT_TEMPLATE = """
<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <title>ExplainHealth AI - Clinical Decision Support Report</title>
    <style>
        body { font-family: 'Helvetica Neue', Helvetica, Arial, sans-serif; color: #1e293b; margin: 40px; background-color: #f8fafc; }
        .card { background: white; border-radius: 12px; padding: 24px; margin-bottom: 24px; box-shadow: 0 4px 6px -1px rgba(0,0,0,0.1); border: 1px solid #e2e8f0; }
        .header { display: flex; justify-content: space-between; align-items: center; border-bottom: 2px solid #0284c7; padding-bottom: 16px; margin-bottom: 24px; }
        .title { color: #0f172a; font-size: 24px; font-weight: bold; }
        .badge { display: inline-block; padding: 4px 12px; border-radius: 9999px; font-size: 14px; font-weight: 600; }
        .badge-elevated { background: #fee2e2; color: #991b1b; }
        .badge-moderate { background: #fef3c7; color: #92400e; }
        .badge-low { background: #dcfce7; color: #166534; }
        table { width: 100%; border-collapse: collapse; margin-top: 12px; }
        th, td { border: 1px solid #cbd5e1; padding: 10px 14px; text-align: left; }
        th { background: #f1f5f9; font-weight: 600; }
        .disclaimer { font-size: 12px; color: #64748b; background: #f8fafc; border-left: 4px solid #0284c7; padding: 12px; margin-top: 32px; }
    </style>
</head>
<body>
    <div class="header">
        <div>
            <div class="title">ExplainHealth AI — Healthcare Risk Assessment Report</div>
            <div style="color: #64748b; font-size: 14px;">Anonymized Patient Profile ID: {{ anonymized_id }}</div>
        </div>
        <div style="text-align: right; color: #64748b; font-size: 14px;">
            Generated: {{ generated_date }}<br>
            System Version: 1.0.0 (Explainable ML Engine)
        </div>
    </div>

    <div class="card">
        <h3>📋 Executive Summary of Multi-Disease Model Estimates</h3>
        <table>
            <thead>
                <tr>
                    <th>Disease Module</th>
                    <th>Model Estimate</th>
                    <th>Risk Category</th>
                    <th>Prediction Confidence</th>
                    <th>Selected Architecture</th>
                </tr>
            </thead>
            <tbody>
                {% for d in summary_list %}
                <tr>
                    <td><strong>{{ d.display_name }}</strong></td>
                    <td><span style="font-size: 16px; font-weight: bold;">{{ d.percentage }}</span></td>
                    <td>
                        <span class="badge {% if d.severity == 'elevated' %}badge-elevated{% elif d.severity == 'moderate' %}badge-moderate{% else %}badge-low{% endif %}">
                            {{ d.risk_tier }}
                        </span>
                    </td>
                    <td>{{ d.uncertainty.confidence_level }}</td>
                    <td>{{ d.selected_model }}</td>
                </tr>
                {% endfor %}
            </tbody>
        </table>
    </div>

    {% for d in summary_list %}
    <div class="card">
        <h3>🔬 Detailed Analysis: {{ d.display_name }}</h3>
        <p><strong>Estimated Model Risk Probability:</strong> {{ d.percentage }} ({{ d.risk_tier }})</p>
        
        <h4>Key Contributing Factors (SHAP Feature Attributions)</h4>
        <p><em>{{ d.shap_explanation.summary_explanation }}</em></p>
        
        {% if d.counterfactuals and d.counterfactuals.scenarios %}
        <h4>What-If Mathematical Simulation</h4>
        <p>Under a <strong>{{ d.counterfactuals.scenarios[0].scenario_name }}</strong>, changing actionable inputs produces an estimated probability of <strong>{{ (d.counterfactuals.scenarios[0].estimated_probability * 100)|round(1) }}%</strong>.</p>
        {% endif %}
    </div>
    {% endfor %}

    <div class="disclaimer">
        <strong>MEDICAL SAFETY & EDUCATIONAL DISCLAIMER:</strong><br>
        This document is an educational decision-support summary generated by machine-learning models trained on public healthcare datasets. 
        It does NOT constitute a clinical diagnosis, medical validation, or prescription of therapy. 
        Always consult a qualified medical professional for diagnosis and clinical treatment recommendations.
    </div>
</body>
</html>
"""

class ClinicalReportService:
    def generate_html_report(
        self,
        anonymized_id: str,
        assessments: List[Dict[str, Any]]
    ) -> str:
        template = Template(REPORT_TEMPLATE)
        summary_list = []
        for a in assessments:
            if a.get("success"):
                summary_list.append({
                    "display_name": a.get("display_name", a.get("disease", "").capitalize()),
                    "percentage": a.get("percentage", "N/A"),
                    "risk_tier": a.get("risk_tier", "N/A"),
                    "severity": a.get("severity", "low"),
                    "uncertainty": a.get("uncertainty", {"confidence_level": "Moderate"}),
                    "selected_model": a.get("selected_model", "Calibrated Ensemble"),
                    "shap_explanation": a.get("shap_explanation", {}),
                    "counterfactuals": a.get("counterfactuals")
                })
                
        html_output = template.render(
            anonymized_id=anonymized_id,
            generated_date=datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC"),
            summary_list=summary_list
        )
        return html_output
